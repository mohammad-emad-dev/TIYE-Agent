'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { validateRun } = require('./validate-reliability');
const { cases } = require('./briefing-cases');
const evidenceDir = path.resolve(__dirname, '../evidence');
const source = path.join(evidenceDir, 'briefing-latest.json');
const output = path.join(evidenceDir, 'briefing-validation.json');
const hash = file => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
fs.writeFileSync(output, JSON.stringify({ passed: false, error: 'Validation did not finish' }, null, 2) + '\n');
const evidence = JSON.parse(fs.readFileSync(source, 'utf8'));
if (evidence.stoppedReason || evidence.runs.length !== cases.length || evidence.plans.length !== cases.length || !evidence.runs.every((run, index) => run.id === cases[index].id && run.index === index + 1 && evidence.plans[index].briefingHash === crypto.createHash('sha256').update(cases[index].briefing.prompt).digest('hex') && evidence.plans[index].recallHash === crypto.createHash('sha256').update(cases[index].briefing.recallPrompt).digest('hex'))) throw new Error('Complete registered briefing trials required');
const sourceHash = hash(source);
const runs = evidence.runs.map(run => ({ id: run.id, ...validateRun(run, path.join(evidenceDir, 'briefing', run.id)) }));
const unchanged = hash(source) === sourceHash;
const validation = { recordedAt: new Date().toISOString(), scope: evidence.scope, sourceHash, runs, unchanged, selectedConfigsUnchanged: evidence.selectedConfigsUnchanged, passed: runs.every(run => run.passed) && unchanged && evidence.selectedConfigsUnchanged };
fs.writeFileSync(output, JSON.stringify(validation, null, 2) + '\n');
console.log(`[briefing-validation] ${validation.passed ? 'PASS' : 'PARTIAL_OR_FAIL'}`);
process.exitCode = validation.passed ? 0 : 1;
